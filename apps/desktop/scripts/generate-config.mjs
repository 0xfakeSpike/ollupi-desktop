// Generates the types of what the sidecar's editing modes print, from the
// JSON Schema the sidecar prints for each:
//
//   src/shared/generated/backend-config.ts  ollupid --check-config (the
//     backend's config.yaml as the sidecar decodes it, and its models as the
//     app selects them), from --config-schema
//   src/shared/generated/backend-skills.ts  ollupid --list-skills and
//     --check-skills (the skills the agent loads), from --skills-schema
//
//   node scripts/generate-config.mjs           write
//   node scripts/generate-config.mjs --check   fail if out of date

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const sidecar = join(here, '../../../sidecar')

const targets = [
  { file: 'backend-config.ts', title: 'ConfigCheck', flag: '--config-schema', output: '--check-config' },
  { file: 'backend-skills.ts', title: 'SkillsCheck', flag: '--skills-schema', output: '--list-skills and --check-skills' },
]

let stale = false
for (const { file, title, flag, output } of targets) {
  const out = join(here, '../src/shared/generated', file)
  const schema = JSON.parse(execFileSync('go', ['run', './cmd/ollupid', flag], { cwd: sidecar, encoding: 'utf8' }))
  const ts = await compile({ ...schema, title }, title, {
    bannerComment: `// Code generated by apps/desktop/scripts/generate-config.mjs from the
// sidecar's ${output} output (ollupid ${flag}). DO NOT EDIT.`,
    additionalProperties: false,
    strictIndexSignatures: true,
    format: true,
  })
  if (process.argv.includes('--check')) {
    let current
    try {
      current = readFileSync(out, 'utf8')
    } catch {}
    if (current !== ts) {
      console.error(`config: ${file} is out of date with the sidecar; run pnpm config:generate`)
      stale = true
    }
  } else {
    mkdirSync(dirname(out), { recursive: true })
    writeFileSync(out, ts)
  }
}
if (stale) process.exit(1)
