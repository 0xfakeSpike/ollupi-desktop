// Generates src/shared/generated/backend-config.ts, the type of the backend's
// config.yaml as the sidecar decodes it, from the JSON Schema the sidecar
// prints for its own config.Config (ollupid --config-schema).
//
//   node scripts/generate-config.mjs           write
//   node scripts/generate-config.mjs --check   fail if out of date

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '../src/shared/generated/backend-config.ts')
const sidecar = join(here, '../../../sidecar')

const schema = JSON.parse(execFileSync('go', ['run', './cmd/ollupid', '--config-schema'], { cwd: sidecar, encoding: 'utf8' }))
const ts = await compile({ ...schema, title: 'BackendConfig' }, 'BackendConfig', {
  bannerComment: `// Code generated by apps/desktop/scripts/generate-config.mjs from the
// sidecar's config.Config (ollupid --config-schema). DO NOT EDIT.`,
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
})

if (process.argv.includes('--check')) {
  let current
  try {
    current = readFileSync(out, 'utf8')
  } catch {}
  if (current !== ts) {
    console.error('config: backend-config.ts is out of date with the sidecar; run pnpm config:generate')
    process.exit(1)
  }
} else {
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, ts)
}
