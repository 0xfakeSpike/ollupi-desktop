// Generates src/generated/ from ollupi's gateway contract,
// gateway/protocol.schema.json, which ollupi produces from the table its
// gateway dispatches from and verifies against real traffic. Nothing here
// reads Go: the types come from the contract's JSON Schema
// (json-schema-to-typescript), and the message maps, error codes, built-in
// tools and providers are read off the contract's other sections.
//
//   node scripts/generate.mjs           write src/generated/
//   node scripts/generate.mjs --check   fail if src/generated/ is out of date

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = join(here, '../src/generated')
const sidecar = join(here, '../../../sidecar')
const check = process.argv.includes('--check')

// The ollupi the sidecar builds against (its go.mod, including a replace).
const ollupi = execFileSync('go', ['list', '-m', '-f', '{{.Dir}}', 'github.com/0xfakeSpike/ollupi'], { cwd: sidecar, encoding: 'utf8' }).trim()
const contractPath = join(ollupi, 'gateway/protocol.schema.json')
const raw = readFileSync(contractPath)
const contract = JSON.parse(raw.toString('utf8'))
// The gateway reports the same digest in initialize (sha256 of the file).
const sha256 = createHash('sha256').update(raw).digest('hex')

const header = `// Code generated by packages/protocol/scripts/generate.mjs from ollupi's
// gateway/protocol.schema.json (sha256 ${sha256}). DO NOT EDIT.
`

const files = {
  'protocol.schema.json': raw.toString('utf8'),
  'types.ts': header + (await types()),
  'messages.ts': header + messages(),
}
const validators = tools()
files['tools.validate.js'] = validators.js
files['tools.validate.d.ts'] = validators.dts
files['tools.ts'] = validators.ts

if (check) {
  const stale = Object.entries(files).filter(([name, content]) => read(join(outDir, name)) !== content)
  if (stale.length) {
    console.error(`protocol: ${stale.map(([n]) => n).join(', ')} out of date with ${contractPath}; run pnpm protocol:generate`)
    process.exit(1)
  }
} else {
  mkdirSync(outDir, { recursive: true })
  for (const [name, content] of Object.entries(files)) writeFileSync(join(outDir, name), content)
}

async function types() {
  const defs = structuredClone(contract.$defs)
  // An object with no properties at all: {} in TypeScript would accept
  // almost anything.
  defs.Empty = { ...defs.Empty, tsType: 'Record<string, never>' }
  const root = {
    $schema: contract.$schema,
    title: 'ProtocolTypes',
    description: 'Every type the contract defines, by name.',
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(Object.keys(defs).map((name) => [name, { $ref: `#/$defs/${name}` }])),
    $defs: defs,
  }
  return compile(root, 'ProtocolTypes', {
    bannerComment: '',
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: true,
  })
}

function messages() {
  const out = [`import type * as T from './types'\n`]
  out.push(`/** The sha256 of the contract these types were generated from. */`)
  out.push(`export const PROTOCOL_SHA256 = '${sha256}'\n`)

  const pairs = (title, doc, section) => {
    out.push(`/** ${doc} */`, `export interface ${title} {`)
    for (const [name, m] of sorted(contract[section])) out.push(`  '${name}': { params: T.${ref(m.params)}; result: T.${ref(m.result)} }`)
    out.push('}\n')
  }
  const singles = (title, doc, section) => {
    out.push(`/** ${doc} */`, `export interface ${title} {`)
    for (const [name, payload] of sorted(contract[section])) out.push(`  '${name}': T.${ref(payload)}`)
    out.push('}\n')
  }
  pairs('ClientMethods', 'Requests the client sends.', 'methods')
  singles('ClientNotifications', 'Notifications the client sends.', 'clientNotifications')
  singles('ServerNotifications', 'Notifications the server pushes.', 'notifications')
  pairs('ServerRequests', 'Requests the server sends and the client answers.', 'serverRequests')

  out.push(`/** JSON-RPC error codes, named as the contract names them. */`, `export const ErrorCode = {`)
  for (const [code, name] of Object.entries(contract.errors).sort((a, b) => a[1].localeCompare(b[1]))) out.push(`  ${name}: ${Number(code)},`)
  out.push('} as const\n', `export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode]\n`)

  out.push(`/** Built-in tools whose arguments or output the contract describes. */`, `export interface BuiltinTools {`)
  for (const [name, t] of sorted(contract.builtinTools)) {
    const parts = Object.entries(t).map(([k, v]) => `${k}: T.${ref(v)}`)
    out.push(`  '${name}': { ${parts.join('; ')} }`)
  }
  out.push('}\n', `export type BuiltinToolName = keyof BuiltinTools\n`)

  out.push(`/** Provider ids ItemRow.server can hold. */`)
  out.push(`export const Providers = [${contract.providers.map((p) => `'${p}'`).join(', ')}] as const\n`)
  out.push(`export type Provider = (typeof Providers)[number]`)
  return out.join('\n') + '\n'
}

// A built-in tool call's arguments are the model's JSON text, and its output
// is only what the contract says once the call completed. tools.ts checks
// them against the contract before the UI reads them. The validators are
// ajv's standalone code, emitted verbatim as tools.validate.js: compiled
// here, so the renderer needs no eval (its CSP forbids it). Formats such as
// date-time are not checked.
function tools() {
  const ajv = new Ajv2020({ code: { source: true, esm: true }, strict: true, formats: { 'date-time': true } })
  ajv.addSchema({ $id: 'ollupi-protocol', $schema: contract.$schema, $defs: contract.$defs })
  const guards = []
  for (const [name, t] of sorted(contract.builtinTools)) {
    for (const [part, schema] of Object.entries(t)) {
      guards.push({ name, part, fn: `${part}_${name.replace(/[^A-Za-z0-9]/g, '_')}`, def: ref(schema) })
    }
  }
  const code = standaloneCode(ajv, Object.fromEntries(guards.map((g) => [g.fn, `ollupi-protocol#/$defs/${g.def}`])))
  const dts = guards.map((g) => `export declare function ${g.fn}(value: unknown): boolean`).join('\n') + '\n'
  const ts = [
    `import type { BuiltinTools } from './messages'`,
    `import * as v from './tools.validate.js'\n`,
    `type Part = 'arguments' | 'output'`,
    `type PartOf<N extends keyof BuiltinTools, P extends Part> = P extends keyof BuiltinTools[N] ? BuiltinTools[N][P] : never\n`,
    `const validators: Record<string, (value: unknown) => boolean> = {`,
    ...guards.map((g) => `  '${g.name}/${g.part}': v.${g.fn},`),
    `}\n`,
    `/** Whether value is a valid \`part\` of built-in tool \`name\`, per the contract. */`,
    `export function isToolPart<N extends keyof BuiltinTools, P extends Part>(name: N, part: P, value: unknown): value is PartOf<N, P> {`,
    `  const validate = validators[\`\${name}/\${part}\`]`,
    `  return !!validate && validate(value)`,
    `}`,
  ].join('\n')
  return { js: '// Generated by packages/protocol/scripts/generate.mjs (ajv standalone). DO NOT EDIT.\n' + code + '\n', dts: header + dts, ts: header + ts + '\n' }
}

function ref(schema) {
  const m = /^#\/\$defs\/([A-Za-z0-9]+)$/.exec(schema?.$ref ?? '')
  if (!m || !contract.$defs[m[1]]) throw new Error(`protocol: expected a $ref to a $defs entry, got ${JSON.stringify(schema)}`)
  return m[1]
}

function sorted(section) {
  if (!section) throw new Error('protocol: the contract is missing a section')
  return Object.entries(section).sort(([a], [b]) => a.localeCompare(b))
}

function read(path) {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return undefined
  }
}
